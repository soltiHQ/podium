// Package proxy provides outbound communication with agents.
//
// The control-plane calls INTO agents to query tasks, submit work, etc.
// Each agent exposes either an HTTP or a gRPC endpoint; the proxy package
// selects the transport based on the endpoint type reported by the agent.
package proxy

import (
	"context"
	"fmt"

	taskv1 "github.com/soltiHQ/control-plane/api/gen/solti/task/v1"
	proxyv1 "github.com/soltiHQ/control-plane/api/proxy/v1"
)

const (
	// MaxTaskIDBytes is the longest task ID a listing page may name. The SDK limits
	// a name to 63 bytes a segment; a page that lists a longer ID than this is
	// refused, as one that could not be decoded.
	MaxTaskIDBytes = 1024

	// MaxTaskConditions is the most conditions a task may hold in an answer, on both
	// transports. An answer with a task that has more is refused, not cut.
	MaxTaskConditions = 64

	// MaxCursorBytes is the longest next cursor a ListTasks page may name; a page
	// that names a longer one is refused.
	MaxCursorBytes = 4096

	// MaxRunPhaseBytes is the longest phase a run of a ListTaskRuns page may name
	// over HTTP, where the phase is a string the agent chooses; the SDK names a word
	// of a few letters. A page that names a longer one is refused, as one that
	// could not be decoded. Over gRPC the phase is an enum.
	MaxRunPhaseBytes = 64

	// maxTaskPage is the most tasks a page holds, and the largest limit a request
	// may name.
	maxTaskPage = 1000
)

// TaskFilter holds optional filters and pagination for listing tasks.
type TaskFilter struct {
	Limit         int
	Offset        int // deprecated: use Cursor
	Cursor        string
	LabelSelector string
	Slot          string
	Status        string
}

// TaskSubmission describes a task to push to an agent.
//
// Spec is a TaskManifest: gRPC carries the protobuf schema, while HTTP uses
// the SDK's CRD JSON representation generated by TaskManifestJSON.
type TaskSubmission struct {
	Spec          *taskv1.TaskManifest
	Preconditions *taskv1.WritePreconditions
}

// AgentProxy is the interface for outbound communication with an agent.
//
// API v1 agents implement the complete TaskService; structured discovery
// capabilities describe workload runners, rather than individual operations.
type AgentProxy interface {
	ListTasks(ctx context.Context, filter TaskFilter) (*proxyv1.ListTasksResponse, error)

	// ApplyTask commits named desired state and returns its stable resource name.
	// Runtime admission and cancellation complete asynchronously on the agent.
	ApplyTask(ctx context.Context, sub TaskSubmission) (taskID string, err error)

	// GetTask returns a single task by ID.
	GetTask(ctx context.Context, taskID string) (*proxyv1.GetTaskResponse, error)
	// ListTaskRuns returns execution history for a specific task.
	ListTaskRuns(ctx context.Context, taskID string) (*proxyv1.ListTaskRunsResponse, error)
	// DeleteTask requests logical termination and purges retained task state.
	// The adapter pins the current UID to avoid deleting a replaced incarnation.
	// Missing tasks return NotFound; the reconciler treats that as already removed.
	DeleteTask(ctx context.Context, taskID string) error

	// StreamTaskLogs subscribes to the live stdout/stderr stream of a task.
	// Returns a channel of typed events (OutputChunk, RunStarted, RunFinished,
	// Lagged). The channel is closed when the agent finishes the stream, the
	// context is cancelled, or the transport drops. Pre-stream errors
	// (dial, bad task id, invalid identity) return immediately and
	// wrap [ErrStreamTaskLogs]; mid-stream errors are surfaced by closing
	// the channel — callers should treat early close as either normal end
	// or transport failure and act accordingly.
	StreamTaskLogs(ctx context.Context, taskID string) (<-chan *taskv1.StreamTaskLogsResponse, error)
}

// TaskCanceler retains desired task state and attempt history while requesting
// the current runtime's logical cancellation. Later reconciliation may resume.
type TaskCanceler interface {
	CancelTask(context.Context, string) error
}

// TaskLogStreamer subscribes to the exact incarnation selected by the caller.
// A stale UID fails instead of following a same-name replacement on reconnect.
type TaskLogStreamer interface {
	StreamTaskLogsForUID(context.Context, string, string) (<-chan *taskv1.StreamTaskLogsResponse, error)
}

func validateTaskFilter(f TaskFilter) error {
	if f.Limit < 0 || f.Limit > maxTaskPage {
		return fmt.Errorf("%w: limit must be 0..%d", ErrListTasks, maxTaskPage)
	}
	if f.Offset != 0 {
		return fmt.Errorf("%w: offset pagination unsupported; use cursor", ErrListTasks)
	}
	if f.Status != "" {
		if _, ok := parseV1TaskStatus(f.Status); !ok {
			return fmt.Errorf("%w: invalid task phase %q", ErrListTasks, f.Status)
		}
	}
	return nil
}

// pageBound is the most items a ListTasks page may hold for a request with this
// limit. A request that names none leaves the page size to the agent, whose pages
// hold maxTaskPage at most.
func pageBound(limit int) int {
	if limit > 0 {
		return limit
	}
	return maxTaskPage
}

// tooManyItems is the error for a page that holds more than limit items.
func tooManyItems(limit int) error {
	return fmt.Errorf("%w: more than %d items", ErrTooManyItems, limit)
}

// tooManyElements is the error for a gRPC answer that holds more repeated elements
// in all than the proxy builds; what says how many.
func tooManyElements(what string) error {
	return fmt.Errorf("%w: %s", ErrTooManyElements, what)
}

// tooManyConditions is the error for a task that holds more than MaxTaskConditions.
// It is no budget of elements: no smaller page avoids the task.
func tooManyConditions() error {
	return fmt.Errorf("%w: a task holds more than %d", ErrTooManyConditions, MaxTaskConditions)
}

// checkCursor refuses a next cursor over MaxCursorBytes. The cursor is not in the
// error: it can be as long as the page.
func checkCursor(cursor string) error {
	if len(cursor) > MaxCursorBytes {
		return fmt.Errorf("%w: next cursor of %d bytes, over %d", ErrCursorTooLong, len(cursor), MaxCursorBytes)
	}
	return nil
}

// checkTaskID refuses a task ID over MaxTaskIDBytes. The ID is not in the error:
// it can be as long as the page.
func checkTaskID(id string) error {
	if len(id) > MaxTaskIDBytes {
		return fmt.Errorf("task ID of %d bytes, over %d", len(id), MaxTaskIDBytes)
	}
	return nil
}

// checkRunPhase refuses a run phase over MaxRunPhaseBytes. The phase is not in the
// error: it can be as long as the page.
func checkRunPhase(phase string) error {
	if len(phase) > MaxRunPhaseBytes {
		return fmt.Errorf("run phase of %d bytes, over %d", len(phase), MaxRunPhaseBytes)
	}
	return nil
}
